// Helper to generate realistic candlestick data
export function generateCandles(basePrice: number, count: number = 40, volatility: number = 0.015): CandleData[] {
  const candles: CandleData[] = [];
  let currentPrice = basePrice * (1 - volatility * (count / 2) * 0.2);
  const now = new Date();

  for (let i = count; i >= 0; i--) {
    const date = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = date.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
    
    // random walk
    const change = (Math.random() - 0.48) * volatility * currentPrice;
    const open = currentPrice;
    const close = Math.max(open + change, 1);
    const high = Math.max(open, close) + Math.random() * volatility * currentPrice * 0.8;
    const low = Math.min(open, close) - Math.random() * volatility * currentPrice * 0.8;
    const volume = Math.floor(Math.random() * 20000000 + 5000000);

    candles.push({
      time: dateStr,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  // Ensure last candle close matches target basePrice roughly
  if (candles.length > 0) {
    candles[candles.length - 1].close = basePrice;
  }

  return candles;
}

export function generateSparkline(basePrice: number, changePercent: number, points: number = 16): number[] {
  const result: number[] = [];
  const startPrice = basePrice / (1 + changePercent / 100);
  const step = (basePrice - startPrice) / (points - 1);
  
  for (let i = 0; i < points; i++) {
    const trend = startPrice + step * i;
    const noise = (Math.random() - 0.5) * (basePrice * 0.012);
    result.push(Number((trend + noise).toFixed(2)));
  }
  result[result.length - 1] = basePrice;
  return result;
}

